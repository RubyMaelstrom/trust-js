#!/usr/bin/env python3
"""Generate the shipped CLDR locales, their inheritance chains and ECMA-402 [[AvailableLocales]].

Writes crates/lumen/src/cldr_locales.rs from CLDR 48 (see scripts/cldr_locales.py):

* CHAINS: each shipped locale with its UTS #35 parent chain (itself first, root excluded);
* AVAILABLE: every available locale tag with the shipped locale whose data it uses.

Usage:
    python3 scripts/gen-cldr-locales.py                  # fetch from the CLDR CDN
    CLDR_DIR=/path/to/cldr-json python3 scripts/...      # read a local cldr-json tree
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cldr_locales  # noqa: E402

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "crates/lumen/src/cldr_locales.rs"


def rust_string(value: str) -> str:
    return json.dumps(value)


def main() -> None:
    shipped = cldr_locales.locales()
    available = cldr_locales.available()
    lines = [
        "//! The CLDR 48 locales Lumen's Intl services ship — GENERATED by",
        "//! scripts/gen-cldr-locales.py. DO NOT EDIT.",
        "//!",
        "//! Every CLDR locale of a supported language is shipped. A regional or script variant",
        "//! stores only what differs from its parent, so data lookups walk the variant's UTS #35",
        "//! parent chain ([`chain`]).",
        "",
        "/// Each shipped locale's parent chain, itself first (root excluded), sorted by locale.",
        "pub static CHAINS: &[(&str, &[&str])] = &[",
    ]
    for locale in shipped:
        chain = ", ".join(rust_string(item) for item in cldr_locales.chain(locale))
        lines.append(f"    ({rust_string(locale)}, &[{chain}]),")
    lines += [
        "];",
        "",
        "/// ECMA-402 [[AvailableLocales]] of every Intl service: each tag with the shipped locale",
        "/// whose data it uses (a default-content tag such as en-US uses en's), sorted by tag.",
        "pub static AVAILABLE: &[(&str, &str)] = &[",
    ]
    for tag in sorted(available):
        lines.append(f"    ({rust_string(tag)}, {rust_string(available[tag])}),")
    lines += [
        "];",
        "",
        "/// The parent chain of a shipped locale (English's for any other).",
        "pub fn chain(locale: &str) -> &'static [&'static str] {",
        "    CHAINS",
        "        .binary_search_by(|row| row.0.cmp(locale))",
        "        .map_or(&[\"en\"], |index| CHAINS[index].1)",
        "}",
        "",
        "/// A locale and its truncations (`pt-AO`, `pt`): the inheritance of components without",
        "/// parent-locale overrides (UTS #35 Part 1), such as plural and day-period rules.",
        "pub fn truncations(locale: &str) -> impl Iterator<Item = &str> {",
        "    std::iter::successors(Some(locale), |current| current.rsplit_once('-').map(|(head, _)| head))",
        "}",
        "",
        "/// The shipped locale holding an available tag's data.",
        "pub fn data_locale(tag: &str) -> Option<&'static str> {",
        "    AVAILABLE",
        "        .binary_search_by(|row| row.0.cmp(tag))",
        "        .ok()",
        "        .map(|index| AVAILABLE[index].1)",
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(shipped)} shipped locales, {len(available)} available tags")


if __name__ == "__main__":
    main()

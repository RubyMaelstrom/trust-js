#!/usr/bin/env python3
"""Generate Intl.ListFormat patterns for every locale TRust JS advertises from CLDR 48.

Source: unicode-org/cldr-json 48.0.0, cldr-misc-full/main/*/listPatterns.json, for every CLDR
locale of a supported language (scripts/cldr_locales.py). A regional or script variant keeps
only the pattern sets that differ from its parent's, and a lookup walks the locale's parent
chain. `CLDR_DIR` names a local copy of the pinned cldr-json tree.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cldr_locales  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates/trust-js/src/cldr_lists.rs"
KINDS = {"conjunction": "standard", "disjunction": "or", "unit": "unit"}
STYLES = ["long", "short", "narrow"]


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    tables: dict[str, dict] = {}
    for locale in cldr_locales.locales():
        data = cldr_locales.read_json(f"cldr-misc-full/main/{locale}/listPatterns.json")
        data = data["main"][locale]["listPatterns"]
        tables[locale] = {}
        for kind, cldr_kind in KINDS.items():
            for style in STYLES:
                suffix = "" if style == "long" else f"-{style}"
                pattern = data[f"listPattern-type-{cldr_kind}{suffix}"]
                values = tuple(pattern[key] for key in ("2", "start", "middle", "end"))
                for value in values:
                    if value.count("{0}") != 1 or value.count("{1}") != 1:
                        raise RuntimeError(f"{locale}/{kind}/{style}: invalid pattern {value!r}")
                    if value.index("{0}") > value.index("{1}"):
                        raise RuntimeError(f"{locale}/{kind}/{style}: reversed placeholders")
                tables[locale][(kind, style)] = values
    rows = sorted(
        (locale, kind, style, values)
        for locale, table in cldr_locales.delta(tables).items()
        for (kind, style), values in table.items()
    )

    output = [
        "//! GENERATED by scripts/gen-cldr-lists.py from CLDR 48. Do not edit.",
        "//! Pair, start, middle, and end patterns for each shipped locale/type/style; a variant",
        "//! holds only what differs from its parent, so lookups walk the locale's parent chain.",
        "",
        "#[rustfmt::skip]",
        "static PATTERNS: &[(&str, &str, &str, [&str; 4])] = &[",
    ]
    for locale, kind, style, values in rows:
        rendered = ", ".join(rust_string(value) for value in values)
        output.append(f'    ("{locale}", "{kind}", "{style}", [{rendered}]),')
    output.extend(
        [
            "];",
            "",
            "pub(crate) fn patterns(locale: &str, kind: &str, style: &str) -> [&'static str; 4] {",
            "    crate::cldr_locales::chain(locale)",
            "        .iter()",
            "        .find_map(|locale| {",
            "            PATTERNS",
            "                .binary_search_by(|row| (row.0, row.1, row.2).cmp(&(locale, kind, style)))",
            "                .ok()",
            "                .map(|index| PATTERNS[index].3)",
            "        })",
            "        .unwrap_or([\"{0} and {1}\", \"{0}, {1}\", \"{0}, {1}\", \"{0}, and {1}\"])",
            "}",
            "",
        ]
    )
    OUTPUT.write_text("\n".join(output), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} pattern sets)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate RelativeTimeFormat phrases/patterns from CLDR 48 resolved date fields.

Source: unicode-org/cldr-json 48.0.0, cldr-dates-full/main/*/dateFields.json, for every CLDR
locale of a supported language (scripts/cldr_locales.py). Tables are sorted and
binary-searched; a regional or script variant keeps only the rows that differ from its
parent's, and a lookup walks the locale's parent chain. `CLDR_DIR` names a local copy of the
pinned cldr-json tree.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cldr_locales  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates/lumen/src/cldr_relative_time.rs"
UNITS = ["year", "quarter", "month", "week", "day", "hour", "minute", "second"]
STYLES = ["long", "short", "narrow"]


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    automatic: dict[str, dict] = {}
    patterns: dict[str, dict] = {}
    for locale in cldr_locales.locales():
        fields = cldr_locales.read_json(f"cldr-dates-full/main/{locale}/dateFields.json")
        fields = fields["main"][locale]["dates"]["fields"]
        automatic[locale] = {}
        patterns[locale] = {}
        for unit in UNITS:
            for style in STYLES:
                key = unit if style == "long" else f"{unit}-{style}"
                field = fields[key]
                for name, phrase in field.items():
                    if name.startswith("relative-type-"):
                        value = int(name.removeprefix("relative-type-"))
                        automatic[locale][(unit, style, value)] = phrase
                for tense in ("past", "future"):
                    group = field[f"relativeTime-type-{tense}"]
                    for name, pattern in group.items():
                        category = name.removeprefix("relativeTimePattern-count-")
                        if pattern.count("{0}") > 1:
                            raise RuntimeError(f"{locale}/{key}/{tense}/{category}: {pattern!r}")
                        patterns[locale][(unit, style, tense, category)] = pattern
    automatic_rows = sorted(
        (locale, *key, value)
        for locale, table in cldr_locales.delta(automatic).items()
        for key, value in table.items()
    )
    pattern_rows = sorted(
        (locale, *key, value)
        for locale, table in cldr_locales.delta(patterns).items()
        for key, value in table.items()
    )
    output = [
        "//! GENERATED by scripts/gen-cldr-relative-time.py from CLDR 48. Do not edit.",
        "//! A variant holds only what differs from its parent; lookups walk the parent chain.",
        "",
        "#[rustfmt::skip]",
        "const AUTO: &[(&str, &str, &str, i8, &str)] = &[",
    ]
    for locale, unit, style, value, phrase in automatic_rows:
        output.append(
            f'    ("{locale}", "{unit}", "{style}", {value}, {rust_string(phrase)}),'
        )
    output.extend(
        ["];", "", "#[rustfmt::skip]", "const PATTERNS: &[(&str, &str, &str, &str, &str, &str)] = &["]
    )
    for locale, unit, style, tense, category, pattern in pattern_rows:
        output.append(
            f'    ("{locale}", "{unit}", "{style}", "{tense}", "{category}", {rust_string(pattern)}),'
        )
    output.extend(
        [
            "];",
            "",
            "pub(crate) fn auto(locale: &str, unit: &str, style: &str, value: i8) -> Option<&'static str> {",
            "    crate::cldr_locales::chain(locale).iter().find_map(|lang| {",
            "        AUTO.binary_search_by(|&(l, u, s, v, _)| (l, u, s, v).cmp(&(lang, unit, style, value)))",
            "            .ok().map(|index| AUTO[index].4)",
            "    })",
            "}",
            "",
            "fn exact_pattern(locale: &str, unit: &str, style: &str, tense: &str, category: &str) -> Option<&'static str> {",
            "    crate::cldr_locales::chain(locale).iter().find_map(|lang| {",
            "        PATTERNS.binary_search_by(|&(l, u, s, t, c, _)|",
            "            (l, u, s, t, c).cmp(&(lang, unit, style, tense, category)))",
            "            .ok().map(|index| PATTERNS[index].5)",
            "    })",
            "}",
            "",
            "pub(crate) fn pattern(locale: &str, unit: &str, style: &str, tense: &str, category: &str) -> Option<&'static str> {",
            "    exact_pattern(locale, unit, style, tense, category)",
            "        .or_else(|| exact_pattern(locale, unit, style, tense, \"other\"))",
            "}",
            "",
        ]
    )
    OUTPUT.write_text("\n".join(output), encoding="utf-8")
    print(
        f"wrote {OUTPUT.relative_to(ROOT)} ({len(automatic_rows)} auto phrases, {len(pattern_rows)} patterns)"
    )


if __name__ == "__main__":
    main()

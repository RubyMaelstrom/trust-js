#!/usr/bin/env python3
"""Generate the Windows time zone mapping from CLDR 48 windowsZones.

Source: unicode-org/cldr-json 48.0.0, cldr-core/supplemental/windowsZones.json (UTS #35 Part 4,
Supplemental Time Zone Data, Windows Zones). Each row maps a Windows time zone key name and a
territory to the territory's default Unicode time zone id (the first of the listed ids);
territory 001 is the Windows zone's default mapping. `CLDR_DIR` names a local copy of the pinned
cldr-json tree.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cldr_locales  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates/lumen/src/cldr_windows_zones.rs"


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    data = cldr_locales.read_json("cldr-core/supplemental/windowsZones.json")
    rows: dict[tuple[str, str], str] = {}
    defaults = set()
    for entry in data["supplemental"]["windowsZones"]["mapTimezones"]:
        zone = entry["mapZone"]
        key = (zone["_other"], zone["_territory"])
        if key in rows:
            raise RuntimeError(f"duplicate windowsZones mapping {key}")
        # "When multiple Unicode time zone IDs are available for a single territory, ... the
        # first entry represents the default mapping for the territory."
        rows[key] = zone["_type"].split()[0]
        if zone["_territory"] == "001":
            defaults.add(zone["_other"])
    missing = {other for other, _ in rows} - defaults
    if missing:
        raise RuntimeError(f"Windows zones without a territory 001 mapping: {sorted(missing)}")

    output = [
        "//! GENERATED by scripts/gen-cldr-windows-zones.py from CLDR 48 windowsZones. Do not edit.",
        "//! UTS #35 Part 4 Windows Zones: (Windows time zone key name, territory) -> the",
        "//! territory's default Unicode time zone id; territory 001 is each Windows zone's default.",
        "",
        "#[rustfmt::skip]",
        "static MAP: &[(&str, &str, &str)] = &[",
    ]
    for (other, territory), zone in sorted(rows.items()):
        output.append(f"    ({rust_string(other)}, {rust_string(territory)}, {rust_string(zone)}),")
    output += [
        "];",
        "",
        "/// The Unicode time zone id CLDR maps a Windows time zone key name to for a territory (an",
        "/// ISO 3166 region code), else the Windows zone's default (territory 001) mapping.",
        "pub(crate) fn unicode_zone(windows_zone: &str, territory: Option<&str>) -> Option<&'static str> {",
        "    let find = |territory: &str| {",
        "        MAP.binary_search_by(|row| (row.0, row.1).cmp(&(windows_zone, territory)))",
        "            .ok()",
        "            .map(|index| MAP[index].2)",
        "    };",
        "    territory.and_then(find).or_else(|| find(\"001\"))",
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(output), encoding="utf-8")
    print(f"{len(rows)} mappings for {len(defaults)} Windows zones")


if __name__ == "__main__":
    main()
